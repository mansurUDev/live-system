import { describe, expect, it } from 'vitest'
import { isTouchDrift, popoverPos } from './popover'

describe('popoverPos — меню в точке вызова, прижатое к краям', () => {
  it('в глубине экрана панель стоит ровно в точке вызова', () => {
    expect(popoverPos(300, 200, 200, 150, 1280, 720)).toEqual({ left: 300, top: 200 })
  })

  it('у правого-нижнего угла прижимается, а не вылезает', () => {
    expect(popoverPos(1250, 700, 200, 150, 1280, 720)).toEqual({ left: 1280 - 200 - 8, top: 720 - 150 - 8 })
  })

  it('точка у самого левого-верхнего края не даёт отрицательных координат', () => {
    expect(popoverPos(2, 3, 200, 150, 1280, 720)).toEqual({ left: 8, top: 8 })
  })

  it('панель шире экрана телефона — остаётся отступ слева, правый край уходит за экран ровно насколько нужно', () => {
    // важен именно левый отступ: начало списка пунктов должно быть видно
    expect(popoverPos(100, 100, 400, 300, 375, 812).left).toBe(8)
  })
})

describe('isTouchDrift — отличаем прокрутку от долгого нажатия', () => {
  it('дрожание пальца в пределах порога — ещё не прокрутка', () => {
    expect(isTouchDrift(100, 100, 106, 94)).toBe(false)
  })

  it('честный свайп по вертикали отменяет меню', () => {
    expect(isTouchDrift(100, 100, 100, 130)).toBe(true)
  })

  it('горизонтальный сдвиг тоже считается', () => {
    expect(isTouchDrift(100, 100, 130, 100)).toBe(true)
  })
})
