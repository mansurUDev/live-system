/**
 * Куда ставить всплывающую панель, вызванную в точке (x, y) — правым кликом
 * или долгим нажатием.
 *
 * Панель растёт вправо-вниз от точки вызова, как системные меню. Если так она
 * вылезает за край экрана, не «переворачиваем» её на другую сторону курсора —
 * просто прижимаем к краю с отступом: перевёрнутое меню накрывало бы палец на
 * телефоне, а прижатое остаётся целиком видимым и предсказуемым.
 */
export function popoverPos(
  x: number,
  y: number,
  w: number,
  h: number,
  vw: number,
  vh: number,
  pad = 8,
): { left: number; top: number } {
  return {
    left: Math.max(pad, Math.min(x, vw - w - pad)),
    top: Math.max(pad, Math.min(y, vh - h - pad)),
  }
}

/** Сдвиг пальца, после которого долгое нажатие считается прокруткой, а не вызовом меню */
export const LONG_PRESS_SLOP_PX = 10

/** Сколько держать палец до открытия меню — как в мессенджерах */
export const LONG_PRESS_MS = 450

/**
 * Превратилось ли касание в прокрутку: палец уехал дальше порога от точки
 * нажатия. Считается по прямым расстояниям осей, чтобы диагональ двух
 * маленьких сдвигов не срабатывала раньше честного свайпа.
 */
export function isTouchDrift(x0: number, y0: number, x1: number, y1: number): boolean {
  return Math.abs(x1 - x0) > LONG_PRESS_SLOP_PX || Math.abs(y1 - y0) > LONG_PRESS_SLOP_PX
}
